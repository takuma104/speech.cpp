"""Writes src/families/pocket-tts/unicode.inc: what the official text rules ask of a character with Python, from the
Unicode of the Python that runs pocket-tts: the code point ranges str.isupper() accepts and str.isdigit() accepts, which
the capital of a text's first letter and the decimal periods of the sentence splitter test, and str.upper() of every
character it changes, which may be several characters.

usage: uv run python gen_unicode.py ../../src/families/pocket-tts/unicode.inc
"""

import sys
import unicodedata


def ranges(accept):
    out, start = [], None
    for cp in range(0x110001):
        inside = cp < 0x110000 and accept(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, rs):
    return f"static const CodepointRange {name}[] = {{\n" + ",\n".join("    {0x%X, 0x%X}" % r for r in rs) + "\n};\n"


def escaped(text):
    return "".join("\\x%02X" % b for b in text.encode("utf-8"))


uppers = ranges(str.isupper)
digits = ranges(str.isdigit)
mapping = [(cp, chr(cp).upper()) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and chr(cp).upper() != chr(cp)]
with open(sys.argv[1], "w") as f:
    f.write(f"// Generated by reference/pocket-tts/gen_unicode.py from Python {sys.version.split()[0]}'s Unicode {unicodedata.unidata_version}.\n")
    f.write(emit("kUppercase", uppers))
    f.write(emit("kDigits", digits))
    f.write("static const UpperMapping kUpperMappings[] = {\n" + ",\n".join(f'    {{0x{cp:X}, "{escaped(u)}"}}' for cp, u in mapping) + "\n};\n")
print(len(uppers), len(digits), len(mapping))
